"""Make the lowrank .caffemodel for NeuOS without pycaffe.

Same SVD split as models/lowrank/lowrank_approx.py (approx_lowrank_weights): each
DxD conv in the config becomes a Dx1 conv (K outputs) followed by a 1xD conv,
using the top-K singular vectors per group. Reads/writes the Caffe protobuf
directly (caffe_pb2 generated by protoc from src/caffe/proto/caffe.proto).

usage: make_lowrank_weights.py PB2_DIR ORIG.caffemodel LOWRANK.prototxt CONFIG.json OUT.caffemodel
"""
import json
import sys

import numpy as np

sys.path.insert(0, sys.argv[1])
import caffe_pb2  # noqa: E402
from google.protobuf import text_format  # noqa: E402

_, _, orig_w, lr_proto, conf_path, out_path = sys.argv
conf = json.load(open(conf_path))

orig = caffe_pb2.NetParameter()
orig.ParseFromString(open(orig_w, "rb").read())
src = {l.name: l for l in orig.layer}
src.update({l.name: l for l in orig.layers})      # old V1 caffemodels (e.g. BVLC CaffeNet)

lr = caffe_pb2.NetParameter()
text_format.Parse(open(lr_proto).read(), lr)
lr_layers = {l.name: l for l in lr.layer}


def blob_array(b):
    shape = list(b.shape.dim) if b.HasField("shape") else [b.num, b.channels, b.height, b.width]
    return np.asarray(b.data, dtype=np.float32).reshape(shape)


def make_blob(arr):
    b = caffe_pb2.BlobProto()
    b.shape.dim.extend(arr.shape)
    b.data.extend(arr.astype(np.float32).ravel())
    return b


out = caffe_pb2.NetParameter()
out.name = lr.name
for layer in lr.layer:
    name = layer.name
    if name in src and name not in conf:          # unchanged layer: copy its blobs
        nl = out.layer.add()
        nl.name, nl.type = name, layer.type
        nl.blobs.extend(src[name].blobs)
for cname, K in conf.items():
    W = blob_array(src[cname].blobs[0])            # (N_total, C, D, D)
    b = blob_array(src[cname].blobs[1])
    g = max(lr_layers[cname + "_v"].convolution_param.group, 1)
    N_total, C, D, _ = W.shape
    N, Kg = N_total // g, K // g
    v_w = np.zeros((K, C, D, 1), np.float32)
    h_w = np.zeros((N_total, Kg, 1, D), np.float32)
    for gi in range(g):
        W_ = W[N * gi:N * (gi + 1)].transpose(1, 2, 3, 0).reshape(C * D, D * N)
        U, S, V = np.linalg.svd(W_, full_matrices=False)
        v = (U[:, :Kg] * np.sqrt(S[:Kg])).reshape(C, D, 1, Kg).transpose(3, 0, 1, 2)
        v_w[Kg * gi:Kg * (gi + 1)] = v
        h = (V[:Kg, :] * np.sqrt(S)[:Kg, None]).reshape(Kg, 1, D, N).transpose(3, 0, 1, 2)
        h_w[N * gi:N * (gi + 1)] = h
        kept = (S[:Kg] ** 2).sum() / (S ** 2).sum()
        print(f"{cname} group {gi}: rank {Kg}/{len(S)}, energy kept {kept:.3f}")
    for suffix, w, bias in (("_v", v_w, np.zeros(K, np.float32)), ("_h", h_w, b.ravel())):
        nl = out.layer.add()
        nl.name, nl.type = cname + suffix, "Convolution"
        nl.blobs.extend([make_blob(w), make_blob(bias)])

open(out_path, "wb").write(out.SerializeToString())
print("wrote", out_path, len(out.layer), "layers")
